    private void btnDetaljiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDetaljiActionPerformed
        int row = tblKupci.getSelectedRow();

        if (row >= 0) {
            try {
                AutoOprema izabranaOprema
                        = ((TableModelAutoOprema) tblKupci
                                .getModel()).getSelectedAutoOprema(row);
                ArrayList<AutoOprema> opremaIzBaze
                        = ClientController.getInstance().getAllAutoOprema(izabranaOprema);

//                JOptionPane.showMessageDialog(this, "Sistem je nasao auto opremu!");
                new FormDetaljiAutoOpreme(this, true, opremaIzBaze.get(0)).setVisible(true);
            } catch (Exception ex) {
                // Ovaj drugi show message za dokumentaciju mozes samo da 
                // ispises negde i slikas.
                JOptionPane.showMessageDialog(this, "Sistem ne moze da nadje auto opremu!",
                        "Obavestenje", JOptionPane.ERROR_MESSAGE);
                Logger.getLogger(FormPretragaAutoOpreme.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_btnDetaljiActionPerformed

