    private void btnDetaljiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDetaljiActionPerformed
        int row = tblKupci.getSelectedRow();

        if (row >= 0) {
            try {
                Kupac izabraniKupac
                        = ((TableModelKupci) tblKupci
                                .getModel()).getSelectedKupac(row);
                // Poslao sam izabranog kupca da bi mi ga vratio iz baze jer moze
                // da se desi da ga obrisemo iz baze rucno, i da on vise ne postoji
                // tako da saljemo zahtev serveru da nam vrati kupca sa tim ID-em
                // U klasi Kupac u dodatniUslov() sam dodao da uradi WHERE
                // za kupacID ako kupacID nije -1 i vraca listu sa 
                // tim jednim kupcem, a kad jeste, 
                // radice WHERE samo za pretragu po imenu, prezimenu, emailu i gradu
                ArrayList<Kupac> kupacIzBaze
                        = ClientController.getInstance().getAllKupac(izabraniKupac);
                // Sledeci show message za "Sistem je nasao kupca!" sam 
                // zakomentarisao, ali to mozes da otkomentarises za odbranu
                // i dokumentaciju u III fazi.

//                JOptionPane.showMessageDialog(this, "Sistem je nasao kupca!");
                // Vratio sam listu sa tim jednim kupcem, zato kupacIzBaze.get(0)
                new FormDetaljiKupca(this, true, kupacIzBaze.get(0)).setVisible(true);
            } catch (Exception ex) {
                // Ovaj drugi show message za dokumentaciju mozes samo da 
                // ispises negde i slikas.
                JOptionPane.showMessageDialog(this, "Sistem ne moze da nadje kupca!",
                        "Obavestenje", JOptionPane.ERROR_MESSAGE);
                Logger.getLogger(FormPretragaKupca.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_btnDetaljiActionPerformed

