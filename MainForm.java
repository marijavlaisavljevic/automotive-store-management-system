    public void popuniKupce() {
        try {
            ArrayList<Kupac> kupci = ClientController.getInstance()
                    .getAllKupac(new Kupac(-1, "", "", "", "", new Grad(0, "")));

            cmbKupac.removeAllItems();

            for (Kupac kupac : kupci) {
                cmbKupac.addItem(kupac);
            }

        } catch (Exception ex) {
            Logger.getLogger(MainForm.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    public void popuniAutoOpremu() {
        try {
            ArrayList<AutoOprema> listaAutoOpreme = ClientController.getInstance()
                    .getAllAutoOprema(new AutoOprema(-1, "", "", 0));

            cmbAutoOprema.removeAllItems();

            for (AutoOprema autoOprema : listaAutoOpreme) {
                cmbAutoOprema.addItem(autoOprema);
            }

        } catch (Exception ex) {
            Logger.getLogger(MainForm.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

